import sys
import time
import unittest
from aqualedger_engine import (
    WaterSensorAttestor,
    MerkleTelemetryTree,
    CleanWaterEscrowSentry,
    PAYOUT_PER_1000_LITERS_USD
)
from aqualedger_agent import (
    AgentFoundryHealthGovernor,
    IoTIngestionAgent,
    PotabilityInvariantAgent,
    EpidemiologicalForecasterAgent,
    FinancialCircuitBreakerAgent,
    PanchayatDispatchAgent
)

if sys.platform == 'win32':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

class TestAquaLedger(unittest.TestCase):

    def setUp(self):
        self.sensor = WaterSensorAttestor("BHARAT_JJM_WELL_ALWAR_001")
        self.escrow = CleanWaterEscrowSentry(initial_escrow_deposit_usd=10000.0)
        self.governor = AgentFoundryHealthGovernor(district="ALWAR_RAJASTHAN")

    def test_01_valid_telemetry_signature(self):
        """Verify HMAC-SHA256 signature generated by sensor is mathematically valid."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.2, 1)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertTrue(ok)
        self.assertEqual(msg, "SUCCESS_FUNDS_DISBURSED")
        self.assertEqual(payout, (500.0 / 1000.0) * PAYOUT_PER_1000_LITERS_USD)

    def test_02_tampered_telemetry_rejection(self):
        """Verify fabricated water data triggers instant cryptographic signature rejection."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.2, 1)
        packet["liters_flowed"] = 50000.0  # Attacker attempts to inflate volume
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertEqual(msg, "ERR_CRYPTOGRAPHIC_SIGNATURE_INVALID")

    def test_03_replay_attack_prevention(self):
        """Verify sequence replay attacks with duplicate sequence numbers are blocked."""
        packet = self.sensor.generate_telemetry_packet(200.0, 7.0, 0.8, 1)
        ok1, _, _ = self.escrow.verify_and_settle_packet(packet)
        self.assertTrue(ok1)

        ok2, payout2, msg2 = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok2)
        self.assertTrue(msg2.startswith("ERR_REPLAY_ATTACK_DETECTED"))
        self.assertEqual(payout2, 0.0)

    def test_04_acidic_contamination_circuit_breaker(self):
        """Verify water with pH < 6.5 triggers instant circuit breaker and freezes payouts."""
        packet = self.sensor.generate_telemetry_packet(300.0, 5.2, 1.0, 2)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertTrue(msg.startswith("ERR_CONTAMINATED_PH"))
        self.assertEqual(payout, 0.0)

    def test_05_alkaline_contamination_circuit_breaker(self):
        """Verify water with pH > 8.5 triggers instant circuit breaker and freezes payouts."""
        packet = self.sensor.generate_telemetry_packet(300.0, 9.1, 1.0, 3)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertTrue(msg.startswith("ERR_CONTAMINATED_PH"))
        self.assertEqual(payout, 0.0)

    def test_06_who_turbidity_threshold_enforcement(self):
        """Verify water with NTU > 5.0 (WHO unpotable threshold) halts funding."""
        packet = self.sensor.generate_telemetry_packet(400.0, 7.4, 7.8, 4)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertTrue(msg.startswith("ERR_HIGH_TURBIDITY"))
        self.assertEqual(payout, 0.0)

    def test_07_flow_spike_anomaly_defense(self):
        """Verify physically impossible flow spikes (>900L/min) are intercepted."""
        packet = self.sensor.generate_telemetry_packet(1500.0, 7.2, 1.1, 5)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertTrue(msg.startswith("ERR_FLOW_RATE_ANOMALY"))
        self.assertEqual(payout, 0.0)

    def test_08_merkle_tree_batch_verification(self):
        """Verify Merkle tree root hash generation and leaf verification across 5 batches."""
        packets = [
            self.sensor.generate_telemetry_packet(100.0, 7.1, 0.9, 10 + i)
            for i in range(5)
        ]
        root_hash = MerkleTelemetryTree.compute_merkle_root(packets)
        self.assertIsInstance(root_hash, str)
        self.assertEqual(len(root_hash), 64)

    def test_09_escrow_balance_depletion(self):
        """Verify escrow pool depletes exactly by disbursed amount on verified clean flows."""
        initial_balance = self.escrow.escrow_vault_usd
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.0, 20)
        self.escrow.verify_and_settle_packet(packet)
        self.assertEqual(self.escrow.escrow_vault_usd, initial_balance - (500.0 / 1000.0 * PAYOUT_PER_1000_LITERS_USD))

    def test_10_sub_millisecond_benchmark(self):
        """Verify 100 consecutive verification and settlement cycles execute in under 5 milliseconds."""
        packets = [
            self.sensor.generate_telemetry_packet(50.0, 7.3, 1.1, 100 + i)
            for i in range(100)
        ]
        t0 = time.perf_counter()
        for p in packets:
            self.escrow.verify_and_settle_packet(p)
        elapsed = time.perf_counter() - t0
        avg_latency_ms = (elapsed / 100.0) * 1000.0
        self.assertLess(avg_latency_ms, 0.10)
        print(f"\n[BENCHMARK] 100 AquaLedger Settlements: {elapsed:.4f}s | Avg Latency: {avg_latency_ms:.4f} ms/tx")

    # ==================== AGENTFOUNDRY AUTONOMOUS TESTS ====================

    def test_11_agentfoundry_clean_water_pass(self):
        """Verify AgentFoundry autonomous loop approves milestone payout on clean water."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.2, 201)
        res = self.governor.process_telemetry(packet)
        self.assertTrue(res["is_potable"])
        self.assertEqual(res["escrow_decision"]["decision"], "MILESTONE_RELEASED")
        self.assertEqual(res["escrow_decision"]["payout_approved_inr"], 105.0)
        self.assertEqual(res["escrow_decision"]["solenoid_valve_state"], "FLOW_ACTIVE")
        self.assertIsNone(res["dispatch"])

    def test_12_agentfoundry_turbidity_surge_intervention(self):
        """Verify AgentFoundry detects pathogen surge and triggers automatic valve shutoff."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.1, 8.5, 202)  # High turbidity surge
        res = self.governor.process_telemetry(packet)
        self.assertFalse(res["is_potable"])
        self.assertEqual(res["escrow_decision"]["decision"], "ESCROW_LOCKED")
        self.assertEqual(res["escrow_decision"]["solenoid_valve_state"], "SHUTOFF_TRIGGERED")
        self.assertIsNotNone(res["dispatch"])
        self.assertEqual(res["dispatch"]["status"], "DISPATCHED_TO_GRAM_PANCHAYAT")
        self.assertIn("Ramesh Kumar", res["dispatch"]["dispatched_to"])

    def test_13_agentfoundry_outbreak_kinetic_forecasting(self):
        """Verify EpidemiologicalForecasterAgent detects monsoon bacterial bloom kinetics."""
        agent = EpidemiologicalForecasterAgent()
        ingest_data = {
            "packet": {"turbidity": 6.8},
            "turbidity_velocity": 2.4
        }
        forecast = agent.forecast_risk(ingest_data)
        self.assertEqual(forecast["alert_level"], "CRITICAL_OUTBREAK_RISK")
        self.assertTrue(forecast["intervention_recommended"])
        self.assertIn("Vibrio cholerae", forecast["predicted_pathogen"])

    def test_14_agentfoundry_escrow_circuit_breaker_freeze(self):
        """Verify FinancialCircuitBreakerAgent enforces sub-millisecond escrow freeze."""
        agent = FinancialCircuitBreakerAgent()
        decision = agent.arbitrate(is_potable=False, outbreak_risk={"intervention_recommended": True}, liters=500.0)
        self.assertEqual(decision["decision"], "ESCROW_LOCKED")
        self.assertEqual(decision["payout_approved_inr"], 0.0)
        self.assertLess(decision["freeze_latency_ms"], 0.05)

    def test_15_agentfoundry_panchayat_repair_dispatch(self):
        """Verify PanchayatDispatchAgent generates compliant SMS ticket for Gram Panchayat."""
        agent = PanchayatDispatchAgent()
        ticket = agent.generate_ticket(
            district="PATNA_BIHAR",
            well_id="WELL_PATNA_09",
            violations=["TURBIDITY_EXCEEDED: 7.2 NTU > 5.0 NTU"],
            outbreak_data={"alert_level": "CRITICAL_OUTBREAK_RISK", "predicted_pathogen": "E. Coli", "intervention_recommended": True}
        )
        self.assertEqual(ticket["priority"], "HIGH")
        self.assertIn("Sunil Verma", ticket["dispatched_to"])
        self.assertIn("WELL_PATNA_09", ticket["sms_payload"])

if __name__ == "__main__":
    unittest.main()
