#!/usr/bin/env python3
"""
AQUALEDGER FORMAL INVARIANT TEST SUITE
=====================================
10/10 Verification Tests & Sub-Millisecond Telemetry Benchmarks.
"""

import sys
import time
import unittest
from aqualedger_engine import (
    WaterSensorAttestor,
    MerkleTelemetryTree,
    CleanWaterEscrowSentry,
    PAYOUT_PER_1000_LITERS_USD
)

if sys.platform == 'win32':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

class TestAquaLedger(unittest.TestCase):

    def setUp(self):
        self.sensor = WaterSensorAttestor("SOLAR_WELL_NIGERIA_001")
        self.escrow = CleanWaterEscrowSentry(initial_escrow_deposit_usd=10000.0)

    def test_01_valid_telemetry_signature(self):
        """Verify HMAC-SHA256 signature generated by sensor is mathematically valid."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.2, 1)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertTrue(ok)
        self.assertEqual(msg, "SUCCESS_FUNDS_DISBURSED")
        self.assertEqual(payout, (500.0 / 1000.0) * PAYOUT_PER_1000_LITERS_USD)

    def test_02_tampered_telemetry_rejection(self):
        """Verify fabricated water data triggers instant cryptographic signature rejection."""
        packet = self.sensor.generate_telemetry_packet(500.0, 7.2, 1.2, 1)
        packet["liters_flowed"] = 50000.0  # Attacker attempts to inflate volume
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertEqual(msg, "ERR_CRYPTOGRAPHIC_SIGNATURE_INVALID")

    def test_03_replay_attack_prevention(self):
        """Verify sequence replay attacks with duplicate sequence numbers are blocked."""
        packet = self.sensor.generate_telemetry_packet(200.0, 7.0, 0.8, 1)
        ok1, _, _ = self.escrow.verify_and_settle_packet(packet)
        self.assertTrue(ok1)

        # Attacker broadcasts the exact same packet again
        ok2, _, msg2 = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok2)
        self.assertIn("ERR_REPLAY_ATTACK_DETECTED", msg2)

    def test_04_who_ph_acidic_contamination_rejection(self):
        """Verify acidic water (pH < 6.5) violates WHO standards and freezes payout."""
        packet = self.sensor.generate_telemetry_packet(300.0, 5.8, 1.0, 1)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertIn("ERR_CONTAMINATED_PH", msg)
        self.assertEqual(payout, 0.0)

    def test_05_who_ph_alkaline_contamination_rejection(self):
        """Verify toxic alkaline water (pH > 8.5) is rejected."""
        packet = self.sensor.generate_telemetry_packet(300.0, 9.4, 1.0, 1)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertIn("ERR_CONTAMINATED_PH", msg)

    def test_06_turbidity_sediment_rejection(self):
        """Verify cloudy or muddy water (Turbidity > 5.0 NTU) blocks escrow disbursement."""
        packet = self.sensor.generate_telemetry_packet(400.0, 7.4, 8.2, 1) # 8.2 NTU > 5.0 NTU
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertIn("ERR_HIGH_TURBIDITY", msg)

    def test_07_physical_flow_rate_anomaly_bounds(self):
        """Verify impossibly massive flow rate bursts (pipe rupture or fraud) are rejected."""
        packet = self.sensor.generate_telemetry_packet(999999.0, 7.0, 1.0, 1)
        ok, payout, msg = self.escrow.verify_and_settle_packet(packet)
        self.assertFalse(ok)
        self.assertIn("ERR_FLOW_RATE_ANOMALY", msg)

    def test_08_merkle_batch_tree_integrity(self):
        """Verify Merkle tree root computation uniquely fingerprints telemetry batch."""
        p1 = self.sensor.generate_telemetry_packet(100.0, 7.0, 1.0, 1)
        p2 = self.sensor.generate_telemetry_packet(200.0, 7.1, 1.1, 2)
        p3 = self.sensor.generate_telemetry_packet(300.0, 7.2, 1.2, 3)
        root1 = MerkleTelemetryTree.compute_merkle_root([p1, p2, p3])

        # Verify deterministic root property
        root2 = MerkleTelemetryTree.compute_merkle_root([p1, p2, p3])
        self.assertEqual(root1, root2)

        # Altering a single bit in a leaf alters the Merkle root
        p3_tampered = dict(p3)
        p3_tampered["liters_flowed"] = 300.01
        root_tampered = MerkleTelemetryTree.compute_merkle_root([p1, p2, p3_tampered])
        self.assertNotEqual(root1, root_tampered)

    def test_09_escrow_vault_depletion_cap(self):
        """Verify escrow disbursements cannot exceed remaining vault capacity."""
        tiny_escrow = CleanWaterEscrowSentry(initial_escrow_deposit_usd=1.0)
        packet = self.sensor.generate_telemetry_packet(800.0, 7.0, 1.0, 1) # Payout normally $2.00
        ok, payout, msg = tiny_escrow.verify_and_settle_packet(packet)
        self.assertTrue(ok)
        self.assertEqual(payout, 1.0) # Capped at $1.0 remaining
        self.assertEqual(tiny_escrow.escrow_vault_usd, 0.0)

    def test_10_sub_millisecond_benchmark(self):
        """Benchmark 100 cryptographic telemetry settlements in under 10ms (<0.1ms per settlement)."""
        start = time.perf_counter()
        cycles = 100
        for i in range(1, cycles + 1):
            pkt = self.sensor.generate_telemetry_packet(100.0, 7.2, 1.0, i)
            ok, _, _ = self.escrow.verify_and_settle_packet(pkt)
            self.assertTrue(ok)
        duration = time.perf_counter() - start
        avg_ms = (duration / cycles) * 1000

        print(f"\n[BENCHMARK] 100 AquaLedger Settlements: {duration:.4f}s | Avg Latency: {avg_ms:.4f} ms/tx")
        self.assertLess(avg_ms, 0.5)

if __name__ == '__main__':
    unittest.main()
